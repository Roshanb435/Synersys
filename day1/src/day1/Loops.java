package day1;

public class Loops {

	public static void main(String[] args) {
		for(int i=1;i<=5;i++)
		{
			System.out.println(i);
			
			
		}
		int x=1;
		int y=3;
		
		//while loop
		while(x<=3)
		{
			System.out.println(x);
			x++;
		}
		
		//infinite loops
		for(;x!=y;)
		{
			System.out.println(x);
		}
		while(x>0)
		{
			System.out.println(x);
		} 
		

	}

}
